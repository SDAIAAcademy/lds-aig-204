def monitoring_rows(rng):
    """26 weeks of synthetic monitoring data for Samt with a seeded deterioration from SHIFT_WEEK and
    a volume spike (renewal season, weeks 9 to 11) that is not a deterioration."""
    rows = []
    for w in range(1, WEEKS + 1):
        conv = int(rng.gauss(38000, 1200))
        if 9 <= w <= 11:
            conv = int(conv * 1.45)
        if w < SHIFT_WEEK:
            p_err, p_fee = 0.03, 0.025
        else:
            k = w - SHIFT_WEEK
            p_err = min(0.075, 0.055 + 0.006 * k)
            p_fee = min(0.12, 0.07 + 0.01 * k)
        err = sum(rng.random() < p_err for _ in range(SAMPLE))
        fee = sum(rng.random() < p_fee for _ in range(60))
        ar_err = sum(rng.random() < 0.028 for _ in range(150))
        en_err = sum(rng.random() < (0.045 if w < SHIFT_WEEK else 0.06) for _ in range(50))
        handover = int(conv * rng.uniform(0.11, 0.13))
        complaints = int(conv * rng.uniform(0.0018, 0.0024) * (1.6 if w >= SHIFT_WEEK + 2 else 1))
        injections = int(rng.gauss(45, 6))
        rows.append([w, conv, SAMPLE, err, 60, fee, 150, ar_err, 50, en_err, handover, complaints, injections])
    return rows


def kri_status(errors_by_week):
    """Apply the K1 rule. Returns a list of 'green', 'amber', 'red' per week."""
    out = []
    for i, e in enumerate(errors_by_week):
        if e >= RED_ERR or (e >= AMBER_ERR and i > 0 and errors_by_week[i - 1] >= AMBER_ERR):
            out.append("red")
        elif e >= AMBER_ERR:
            out.append("amber")
        else:
            out.append("green")
    return out


