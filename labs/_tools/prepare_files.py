FIXED = (2026, 11, 1, 0, 0, 0)


def save_xlsx(wb, path):
    """Save with fixed timestamps so the bytes do not change between runs."""
    import datetime
    wb.properties.created = datetime.datetime(2026, 11, 1)
    wb.properties.modified = datetime.datetime(2026, 11, 1)
    wb.properties.creator = "LDS-AIG-204"
    buf = io.BytesIO()
    wb.save(buf)
    src = zipfile.ZipFile(io.BytesIO(buf.getvalue()))
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for info in sorted(src.infolist(), key=lambda i: i.filename):
            zi = zipfile.ZipInfo(info.filename, date_time=FIXED)
            zi.compress_type = zipfile.ZIP_DEFLATED
            data = src.read(info.filename)
            if info.filename == "docProps/core.xml":
                import re
                data = re.sub(rb"<dcterms:(created|modified)([^>]*)>[^<]*<", rb"<dcterms:\1\2>2026-11-01T00:00:00Z<", data)
            z.writestr(zi, data)
    path.write_bytes(out.getvalue())


def sheet(path, header, rows, title="ورقة", widths=None, extra=None):
    wb = Workbook()
    ws = wb.active
    ws.title = title
    ws.sheet_view.rightToLeft = True
    ws.append(header)
    for c in ws[1]:
        c.font = Font(bold=True)
        c.fill = PatternFill("solid", fgColor="DDEBF7")
    for r in rows:
        ws.append(list(r))
    for i, w in enumerate(widths or [18] * len(header)):
        ws.column_dimensions[chr(65 + i) if i < 26 else "A"].width = w
    if extra:
        for name, hdr, rws in extra:
            ws2 = wb.create_sheet(name)
            ws2.sheet_view.rightToLeft = True
            ws2.append(hdr)
            for c in ws2[1]:
                c.font = Font(bold=True)
            for r in rws:
                ws2.append(list(r))
    save_xlsx(wb, path)


